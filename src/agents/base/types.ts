// Normal agents (available to all paid plans)
export type NormalAgentType =
  | "leads"
  | "content"
  | "partners"
  | "contracts"
  | "compliance"
  | "receivables"
  | "spend"
  | "pricing";

// All agent types including Superagent (yearly plans only)
export type AgentType = NormalAgentType | "superagent";

// List of normal agent types for iteration
export const NORMAL_AGENT_TYPES: NormalAgentType[] = [
  "leads",
  "content",
  "partners",
  "contracts",
  "compliance",
  "receivables",
  "spend",
  "pricing",
];

export interface AgentTask {
  id: string;
  action: string;
  params: Record<string, unknown>;
  priority: "low" | "normal" | "high" | "urgent";
  metadata?: Record<string, unknown>;
}

export interface AgentResult {
  success: boolean;
  data?: unknown;
  error?: string;
  creditsUsed?: number;
}

export interface AgentEvent {
  id: string;
  fromAgent: AgentType;
  toAgent?: AgentType;
  eventType: string;
  payload: Record<string, unknown>;
  timestamp: Date;
}

export interface CreditCost {
  [action: string]: number;
}

export interface AgentConfig {
  enabled: boolean;
  settings: Record<string, unknown>;
}

